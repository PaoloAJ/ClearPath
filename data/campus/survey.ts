// Builds SURVEY.md, a printable checklist of every feature flagged needs_survey. Items on a
// demo route (Library West ↔ Marston, with and without stairs or the elevator) come first; the
// rest are grouped by nearest demo building, ordered north to south.
// Run with `pnpm tsx data/campus/survey.ts` after clearing flags to refresh the sheet.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

type Position = [number, number];
type Props = Record<string, unknown>;
type Feature<G> = { type: 'Feature'; properties: Props; geometry: G };
type Collection<G> = { type: 'FeatureCollection'; features: Feature<G>[] };

const here = dirname(fileURLToPath(import.meta.url));
const nodes = read<{ coordinates: Position }>('nodes.geojson').features;
const edges = read<{ coordinates: Position[] }>('edges.geojson').features;

const DEMO_AREA = 'the demo routes: walk these first';
const BUILDING_ORDER = [DEMO_AREA, 'Library West', 'Turlington', 'CSE', 'Marston'];
const CHECKS: Record<string, string> = {
  slope: 'Grade (phone level app). Positive = uphill from start to end.',
  surface: 'Surface: paved / brick / gravel / grass.',
  elevator_connection: 'Does this elevator link these two entrances? Step-free both ends?',
};

const entrances = nodes.filter((n) => n.properties.kind === 'entrance' && n.properties.building);

const onDemoRoute = demoRouteEdges();

type Item = { area: string; lat: number; lng: number; line: string };
const items: Item[] = [];

for (const e of edges) {
  const flags = (e.properties.needs_survey as string[] | undefined) ?? [];
  if (!flags.length) continue;
  const c = e.geometry.coordinates;
  const mid = c[Math.floor(c.length / 2)]!;
  const length = lengthMeters(c);
  const tags = [e.properties.stairs ? 'stairs' : null, e.properties.surface, e.properties.indoor ? 'indoor' : null]
    .filter(Boolean)
    .join(', ');
  items.push({
    area: onDemoRoute.has(e.properties.id) ? DEMO_AREA : nearestBuilding(mid),
    lat: mid[1],
    lng: mid[0],
    line:
      `- [ ] **Edge ${e.properties.id}** · ${Math.round(length)} m · ${tags} · ` +
      `[map](${mapLink(mid)})${e.properties.osm_way ? ` · [OSM](https://www.openstreetmap.org/way/${e.properties.osm_way})` : ''}\n` +
      flags.map((f) => `  - ${CHECKS[f] ?? f}`).join('\n'),
  });
}

for (const n of nodes) {
  const flags = (n.properties.needs_survey as string[] | undefined) ?? [];
  if (!flags.length) continue;
  const at = n.geometry.coordinates;
  items.push({
    area: String(n.properties.building ?? nearestBuilding(at)),
    lat: at[1],
    lng: at[0],
    line:
      `- [ ] **Node ${n.properties.id}** (${n.properties.kind}${n.properties.elevator_name ? `: ${n.properties.elevator_name}` : ''}) · ` +
      `[map](${mapLink(at)})\n` +
      flags.map((f) => `  - ${CHECKS[f] ?? f}`).join('\n'),
  });
}

const out = [
  '# Campus survey sheet',
  '',
  `Generated by \`data/campus/survey.ts\` from the \`needs_survey\` flags. ${items.length} items. Walk it north to south, from Library West to Marston.`,
  '',
  'For each item: check it, fix the fields in `nodes.geojson` / `edges.geojson`, remove the flag, then rerun `pnpm tsx data/campus/survey.ts` and `make seed`. While you walk, also note anything the graph misses: missing curb cuts (→ `stairs: true`), broken ramps, and step-free approaches to Library West\'s raised plaza. See `data/campus/README.md`.',
  '',
];
for (const area of [...BUILDING_ORDER, ...new Set(items.map((i) => i.area))]) {
  const group = items.filter((i) => i.area === area).sort((a, b) => b.lat - a.lat || a.lng - b.lng);
  const heading = area === DEMO_AREA ? `## On ${area} (${group.length})` : `## Near ${area} (${group.length})`;
  if (!group.length || out.includes(heading)) continue;
  out.push(heading, '', ...group.map((i) => i.line), '');
}
writeFileSync(join(here, 'SURVEY.md'), out.join('\n'));
console.log(`wrote SURVEY.md: ${items.length} items`);

function read<G>(file: string): Collection<G> {
  return JSON.parse(readFileSync(join(here, file), 'utf8')) as Collection<G>;
}

/** Edges on any shortest route between a Library West and a Marston entrance, with stairs and
 * the elevator each allowed or not. Those are the routes the demo and usability tasks use. */
function demoRouteEdges(): Set<unknown> {
  const adjacency = new Map<unknown, { to: unknown; edge: Feature<{ coordinates: Position[] }>; length: number }[]>();
  for (const e of edges) {
    const length = lengthMeters(e.geometry.coordinates);
    for (const [a, b] of [[e.properties.source, e.properties.target], [e.properties.target, e.properties.source]]) {
      adjacency.set(a, [...(adjacency.get(a) ?? []), { to: b, edge: e, length }]);
    }
  }
  const starts = entrances.filter((n) => n.properties.building === 'Library West').map((n) => n.properties.id);
  const ends = entrances.filter((n) => n.properties.building === 'Marston').map((n) => n.properties.id);
  const variants: ((p: Props) => boolean)[] = [
    () => true,
    (p) => !p.stairs,
    (p) => p.elevator_id == null,
    (p) => !p.stairs && p.elevator_id == null,
  ];

  const result = new Set<unknown>();
  for (const allowed of variants) {
    for (const from of starts) {
      // Dijkstra; the graph is a few hundred nodes, so a linear scan for the minimum is fine.
      const dist = new Map<unknown, number>([[from, 0]]);
      const prev = new Map<unknown, { node: unknown; edgeId: unknown }>();
      const done = new Set<unknown>();
      for (;;) {
        let u: unknown;
        let best = Infinity;
        for (const [node, d] of dist) if (!done.has(node) && d < best) [u, best] = [node, d];
        if (u === undefined) break;
        done.add(u);
        for (const { to, edge, length } of adjacency.get(u) ?? []) {
          if (!allowed(edge.properties) || best + length >= (dist.get(to) ?? Infinity)) continue;
          dist.set(to, best + length);
          prev.set(to, { node: u, edgeId: edge.properties.id });
        }
      }
      for (const to of ends) {
        for (let at = to, step = prev.get(at); step; at = step.node, step = prev.get(at)) result.add(step.edgeId);
      }
    }
  }
  return result;
}

function nearestBuilding(at: Position): string {
  let best = '';
  let bestD = Infinity;
  for (const n of entrances) {
    const d = haversine(at, n.geometry.coordinates);
    if (d < bestD) {
      bestD = d;
      best = String(n.properties.building);
    }
  }
  return best;
}

function mapLink([lng, lat]: Position): string {
  return `https://www.openstreetmap.org/?mlat=${lat}&mlon=${lng}#map=20/${lat}/${lng}`;
}

function lengthMeters(coords: Position[]): number {
  let total = 0;
  for (let i = 1; i < coords.length; i++) total += haversine(coords[i - 1]!, coords[i]!);
  return total;
}

function haversine([lng1, lat1]: Position, [lng2, lat2]: Position): number {
  const R = 6_371_000;
  const rad = Math.PI / 180;
  const dLat = (lat2 - lat1) * rad;
  const dLng = (lng2 - lng1) * rad;
  const a = Math.sin(dLat / 2) ** 2 + Math.cos(lat1 * rad) * Math.cos(lat2 * rad) * Math.sin(dLng / 2) ** 2;
  return 2 * R * Math.asin(Math.sqrt(a));
}
